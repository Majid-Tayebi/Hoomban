export function citiesForProvince(province: string): readonly string[] {
	return IRAN_CITIES_BY_PROVINCE[province] ?? [];
}

export function isValidProvince(province: string): boolean {
	return (IRAN_PROVINCES as readonly string[]).includes(province);
}

export function isValidCityForProvince(province: string, city: string): boolean {
	if (!city.trim()) return false;
	return citiesForProvince(province).includes(city);
}
